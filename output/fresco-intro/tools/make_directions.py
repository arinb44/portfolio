"""Writes the three direction pages: the built home page (dist/index.html, from `npm run build`) with the intro added.
Run from the project root after a build: python -I output/fresco-intro/tools/make_directions.py
The home page parts point at the copies in directions/shared/home/ and at public/ (the static server runs at the project root).
"""
import re

DIRS = {'a-starlight': ('a', 'A: Starlight'), 'b-pigment': ('b', 'B: Pigment on plaster'), 'c-looking-up': ('c', 'C: Looking up')}
html = open('dist/index.html', encoding='utf8').read()
body = html[html.index('<body>') + 6:html.index('<script type="module"')]
body = body.replace('"/creation/', '"/public/creation/')
assert body.count('<header class="site">') == 1
body = body.replace('<header class="site">', '<canvas id="intro" aria-hidden="true"></canvas><header class="site">')

for folder, (key, name) in DIRS.items():
    page = f'''<!doctype html>
<!-- Fresco intro, direction {name}. Generated by tools/make_directions.py from the built home page; edit the generator, not this file. -->
<html lang="en" class="static revealed">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Fresco intro · {name}</title>
<link rel="icon" href="/public/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="../shared/home/tokens.css"><link rel="stylesheet" href="../shared/home/creation.css"><link rel="stylesheet" href="../shared/intro.css">
<script>document.documentElement.classList.remove('static', 'revealed');</script>
</head>
<body><button class="skip-intro" type="button">Skip intro</button>{body}<script type="module">
  import {{ playIntro }} from '../shared/intro.js';
  import {{ startPage }} from '../shared/home/home.js';
  const intro = playIntro({{ direction: '{key}' }});
  startPage({{ look: {{ glow: 1, twinkle: 1, spark: [0.784, 0.635, 0.29] }}, data: '/public/creation/', hold: intro.done }});
</script>
</body>
</html>
'''
    import os; os.makedirs(f'output/fresco-intro/directions/{folder}', exist_ok=True)
    open(f'output/fresco-intro/directions/{folder}/index.html', 'w', encoding='utf8').write(page)
    print(folder)
